#!/usr/bin/env bash
set -Eeuo pipefail
readonly ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
readonly INSTALL_DIR="${OPENHTPC_INSTALL_DIR:-$HOME/.local/lib/openhtpc}"
readonly INSTALLED_MANIFEST="$INSTALL_DIR/.openhtpc-managed-files"
readonly TARGET_MANIFEST="$ROOT/payload/managed-files.txt"
readonly LEGACY_DEV27_MANIFEST="$ROOT/legacy-managed-files-dev27.txt"
# Refuse a broken candidate before locks, runtime cleanup or any installed-file mutation.
python3 "$ROOT/payload/openhtpc-preflight-payload.py" --payload "$ROOT/payload" ||
    { printf '[OPENHTPC] Paquet incomplet : mise à jour refusée avant modification.\n' >&2; exit 41; }

printf '[OPENHTPC] Mise à jour ciblée : configuration, Hardware Passport et dépendances existantes seront conservés.\n'

# A dry-run must be genuinely non-mutating: do not stop a live OPENHTPC session
# before delegating --check to the installer.
for arg in "$@"; do
    if [[ $arg == "--check" ]]; then
        export OPENHTPC_UPDATE_MODE=1
        exec "$ROOT/install.sh" "$@"
    fi
done

# Fail closed if an earlier update was interrupted (SIGKILL/power loss).
# Never try to repair an unknown partially-installed tree automatically.
# Require explicit offline recovery from the preserved snapshot first.
for abandoned in "$HOME"/.local/state/openhtpc/upgrade-rollback.*; do
    [[ -e $abandoned || -L $abandoned ]] || continue
    printf '[OPENHTPC] RECOVERY REQUIRED: an earlier update left an unfinished backup at %s\n' "$abandoned" >&2
    printf '[OPENHTPC] Update refused; inspect with python3 %s/recover.py --inspect or safely restore with --restore (offline).\n' "$ROOT" >&2
    exit 43
done

# Validate every managed path and its ancestors BEFORE taking playback locks
# or modifying HOME. This rejects external XDG roots and symlinked parents.
if ! python3 "$ROOT/recover.py" --check-paths; then
    printf '[OPENHTPC] UPDATE REFUSED: unsafe managed HOME path.\n' >&2
    exit 42
fi

# Refuse an in-place update while any authoritative playback is active, and
# hold the same lock for the whole update so a new playback cannot start after
# this preflight.  Keep the legacy DVD lock as a transition guard for older
# installed dispatchers which do not yet know playback-active.lock.
playback_lock="$HOME/.local/state/openhtpc/playback-active.lock"
dvd_lock="$HOME/.local/state/openhtpc/play-dvd.lock"
mkdir -p "$(dirname "$playback_lock")"
exec 7>"$playback_lock"
if ! flock -n 7; then
    printf '[OPENHTPC] ERREUR : une lecture est en cours. Arrêtez la lecture avant de mettre OPENHTPC à jour.\n' >&2
    exit 4
fi
exec 8>"$dvd_lock"
if ! flock -n 8; then
    printf '[OPENHTPC] ERREUR : une lecture DVD est en cours. Arrêtez la lecture avant de mettre OPENHTPC à jour.\n' >&2
    exit 4
fi
# File descriptors 7 and 8 intentionally remain locked until update.sh exits.

# Remember whether the appliance session was running before update cleanup.
# A successful in-place update must restore the same user-visible state instead
# of leaving Plasma in appliance mode with no Flex window.
was_running=0
restart_required=0
runtime_state="$HOME/.local/state/openhtpc/runtime-session.json"
if [[ -r $runtime_state ]] && python3 - "$runtime_state" <<'PY_STATE'
import json, pathlib, sys
try:
    data=json.loads(pathlib.Path(sys.argv[1]).read_text(encoding="utf-8"))
except (OSError, ValueError, TypeError):
    raise SystemExit(1)
raise SystemExit(0 if data.get("state") == "RUNNING" else 1)
PY_STATE
then
    was_running=1
fi

# Candidate rollback: protect the pre-update installed tree and 3 legacy files.
# This does NOT provide system-wide transactionality or restore external desktop links.
rollback_root=""
rollback_ready=0
rollback_had_install=0
restore_managed_snapshot() {
    local okay=0 item i
    # The install directory must remain inside the fixed, expected HOME path.
    if [[ $INSTALL_DIR != "$HOME/.local/lib/openhtpc" || -L $INSTALL_DIR ]]; then
        printf '[OPENHTPC] ROLLBACK BLOCKED: unexpected install path or symlink; snapshot retained: %s\n' "$rollback_root" >&2
        return 1
    fi
    if (( rollback_had_install )); then
        if rm -rf -- "$INSTALL_DIR" && mv -- "$rollback_root/installed" "$INSTALL_DIR"; then :; else okay=1; fi
    else
        if ! rm -rf -- "$INSTALL_DIR"; then okay=1; fi
    fi
    for i in 0 1 2; do
        item="${rollback_legacy[$i]}"
        # Restore absence as well as presence: an aborted installer may have
        # created a legacy path that did not exist before the upgrade.
        if [[ -d $item && ! -L $item ]]; then okay=1; continue; fi
        if ! rm -f -- "$item"; then okay=1; continue; fi
        if [[ -e $rollback_root/legacy/$i || -L $rollback_root/legacy/$i ]]; then
            mkdir -p -- "$(dirname -- "$item")"
            if ! cp -a -- "$rollback_root/legacy/$i" "$item"; then okay=1; fi
        fi
    done
    # Restore the critical runtime outputs regenerated by the installer.
    # A directory originally absent must be removed after a failed update.
    for i in "${!rollback_runtime_paths[@]}"; do
        item="${rollback_runtime_paths[$i]}"
        # Never traverse symlinked parent directories when deleting a runtime tree.
        if [[ -L $HOME/.config || -L $HOME/.config/openhtpc ||
              -L $HOME/.local || -L $HOME/.local/state ||
              -L $HOME/.local/state/openhtpc ]]; then
            okay=1; continue
        fi
        if [[ -d $item && ! -L $item ]]; then
            if ! rm -rf -- "$item"; then okay=1; continue; fi
        elif ! rm -f -- "$item"; then
            okay=1; continue
        fi
        if [[ -e $rollback_root/runtime/$i || -L $rollback_root/runtime/$i ]]; then
            mkdir -p -- "$(dirname -- "$item")"
            if ! cp -a -- "$rollback_root/runtime/$i" "$item"; then okay=1; fi
        fi
    done
    # Restore known entrypoints the installer can change outside INSTALL_DIR.
    for i in "${!rollback_external[@]}"; do
        item="${rollback_external[$i]}"
        if [[ -d $item && ! -L $item ]]; then okay=1; continue; fi
        if ! rm -f -- "$item"; then okay=1; continue; fi
        if [[ -e $rollback_root/external/$i || -L $rollback_root/external/$i ]]; then
            mkdir -p -- "$(dirname -- "$item")"
            if ! cp -a -- "$rollback_root/external/$i" "$item"; then okay=1; fi
        fi
    done
    if (( okay )); then
        printf '[OPENHTPC] ROLLBACK INCOMPLETE: recovery snapshot retained at %s\n' "$rollback_root" >&2
        return 1
    fi
    printf '[OPENHTPC] Managed tree and 3 legacy paths restored after update error.\n' >&2
}

restore_preupdate_session_on_exit() {
    local rc=$?
    if (( rollback_ready )); then
        if (( rc != 0 )); then
            if restore_managed_snapshot; then
                rm -rf -- "$rollback_root"
            else
                printf '[OPENHTPC] MANUAL RECOVERY REQUIRED: %s\n' "$rollback_root" >&2
            fi
        else
            rm -rf -- "$rollback_root"
        fi
        rollback_ready=0
    fi
    if (( rc != 0 && was_running && restart_required )); then
        trap - EXIT
        if [[ -x $INSTALL_DIR/openhtpc ]]; then
            if "$INSTALL_DIR/openhtpc" start; then
                printf '[OPENHTPC] Échec de mise à jour : session OPENHTPC précédente restaurée.\n' >&2
            else
                printf '[OPENHTPC] ERREUR : échec de mise à jour et impossible de restaurer automatiquement OPENHTPC.\n' >&2
            fi
        else
            printf '[OPENHTPC] ERREUR : échec de mise à jour et lanceur OPENHTPC indisponible pour restauration.\n' >&2
        fi
        exit "$rc"
    fi
}
trap restore_preupdate_session_on_exit EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
trap 'exit 129' HUP

# Snapshot before the destructive cleanup, fail closed if anything is missing.
if [[ $INSTALL_DIR != "$HOME/.local/lib/openhtpc" || -L $INSTALL_DIR ]]; then
    printf '[OPENHTPC] UPDATE REFUSED: unexpected install location or symlink.\n' >&2
    exit 42
fi
rollback_legacy=(
    "$HOME/.config/openhtpc/media-browser.ini"
    "$HOME/.config/openhtpc/media-browser-paths.json"
    "$HOME/.local/state/openhtpc/media-model.json"
)
rollback_root="$(mktemp -d -- "$HOME/.local/state/openhtpc/upgrade-rollback.XXXXXXXX")" || exit 42
mkdir -p -- "$rollback_root/legacy"
if [[ -d $INSTALL_DIR ]]; then
    if ! cp -a -- "$INSTALL_DIR" "$rollback_root/installed"; then
        rm -rf -- "$rollback_root"; exit 42
    fi
    rollback_had_install=1
fi
for i in 0 1 2; do
    item="${rollback_legacy[$i]}"
    if [[ -e $item || -L $item ]]; then
        if ! cp -a -- "$item" "$rollback_root/legacy/$i"; then
            rm -rf -- "$rollback_root"; exit 42
        fi
    fi
done
# Preserve known external launchers, including whether each path was absent.
rollback_external=(
    "$HOME/.local/bin/openhtpc-builder"
    "$HOME/.local/bin/openhtpc-player-test"
    "$HOME/.local/bin/openhtpc-session-start"
    "$HOME/.local/bin/openhtpc-media-browser"
    "$HOME/.local/bin/openhtpc"
    "$HOME/.local/bin/openhtpc-validator"
    "$HOME/.config/autostart/openhtpc.desktop"
    "$HOME/.config/autostart/openhtpc-flex.desktop"
    "${XDG_DATA_HOME:-$HOME/.local/share}/applications/openhtpc.desktop"
)
mkdir -p -- "$rollback_root/external"
for i in "${!rollback_external[@]}"; do
    item="${rollback_external[$i]}"
    if [[ -d $item && ! -L $item ]]; then
        printf '[OPENHTPC] UPDATE REFUSED: managed launcher path is a directory: %s\n' "$item" >&2
        rm -rf -- "$rollback_root"; exit 42
    fi
    if [[ -e $item || -L $item ]]; then
        if ! cp -a -- "$item" "$rollback_root/external/$i"; then
            rm -rf -- "$rollback_root"; exit 42
        fi
    fi
done
# Snapshot runtime outputs that refresh/rebuild modifies outside INSTALL_DIR.
# Do not touch media sources, checkpoints, movie indexes or personal MPV config.
rollback_runtime_paths=(
    "$HOME/.config/openhtpc/profile.json"
    "$HOME/.config/openhtpc/runtime"
    "$HOME/.local/state/openhtpc/capability-validation.json"
)
if [[ -L $HOME/.config || -L $HOME/.config/openhtpc ||
      -L $HOME/.local || -L $HOME/.local/state ||
      -L $HOME/.local/state/openhtpc ]]; then
    printf '[OPENHTPC] UPDATE REFUSED: symlinked runtime parent.\n' >&2
    rm -rf -- "$rollback_root"; exit 42
fi
mkdir -p -- "$rollback_root/runtime"
for i in "${!rollback_runtime_paths[@]}"; do
    item="${rollback_runtime_paths[$i]}"
    if [[ -L $item ]]; then
        printf '[OPENHTPC] UPDATE REFUSED: symlinked runtime target: %s\n' "$item" >&2
        rm -rf -- "$rollback_root"; exit 42
    fi
    if [[ -e $item ]]; then
        if ! cp -a -- "$item" "$rollback_root/runtime/$i"; then
            rm -rf -- "$rollback_root"; exit 42
        fi
    fi
done
# Durably seal the full snapshot BEFORE any destructive cleanup. A kill before
# this marker is a non-recoverable incomplete snapshot, not a restore license.
if ! python3 "$ROOT/recover.py" --seal "$rollback_root"; then
    printf '[OPENHTPC] Unable to seal rollback snapshot; update refused.\n' >&2
    exit 42
fi
rollback_ready=1

# From this point onward, a failed mutation must attempt to restore the session
# that was active before cleanup.
if (( was_running )); then
    restart_required=1
fi

if [[ -x $ROOT/payload/openhtpc-runtime.py ]]; then
    if ! OPENHTPC_INSTALL_DIR="${OPENHTPC_INSTALL_DIR:-$HOME/.local/lib/openhtpc}" \
        "$ROOT/payload/openhtpc-runtime.py" cleanup-legacy >/dev/null; then
        printf '[OPENHTPC] ERREUR : impossible de stabiliser les anciens processus OPENHTPC.\n' >&2
        exit 1
    fi
fi
if [[ -d $INSTALL_DIR ]]; then
    previous_manifest=$INSTALLED_MANIFEST
    if [[ ! -f $previous_manifest ]]; then
        previous_manifest=$LEGACY_DEV27_MANIFEST
    fi
    [[ -r $previous_manifest && -r $TARGET_MANIFEST ]] || {
        printf '[OPENHTPC] ERREUR : manifeste de fichiers gérés absent; nettoyage refusé.\n' >&2
        exit 1
    }
    python3 "$ROOT/payload/openhtpc-update-managed-files" \
        --install-dir "$INSTALL_DIR" --previous "$previous_manifest" --target "$TARGET_MANIFEST"
fi
# RC23 invalidates only RC22's obsolete standalone MEDIA UI artifacts.
# User configuration, media roots and playback history remain untouched.
rm -f -- "$HOME/.config/openhtpc/media-browser.ini" \
    "$HOME/.config/openhtpc/media-browser-paths.json" \
    "$HOME/.local/state/openhtpc/media-model.json"
export OPENHTPC_UPDATE_MODE=1
"$ROOT/install.sh" "$@"

if (( was_running )); then
    "$INSTALL_DIR/openhtpc" start
    restart_required=0
    printf '[OPENHTPC] Session active avant mise à jour : OPENHTPC relancé automatiquement.\n'
fi
